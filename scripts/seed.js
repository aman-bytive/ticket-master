#!/usr/bin/env node
'use strict';

// Seeds two events for load testing: one small, one large.
// Usage:
//   DB_HOST=localhost DB_PORT=5432 DB_USER=ticketmaster DB_PASSWORD=ticketmaster DB_NAME=ticketmaster \
//     node scripts/seed.js [--counts 50,50000]

const { Client } = require('pg');

function parseArgs(argv) {
  const args = { counts: [50, 50000] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--counts') {
      args.counts = argv[++i].split(',').map((n) => parseInt(n, 10));
    }
  }
  return args;
}

async function seedEvent(client, ticketCount) {
  const venue = await client.query(
    `INSERT INTO venues (name, location, seat_map) VALUES ($1, $2, $3) RETURNING id`,
    [`Seed Venue (${ticketCount})`, 'Nowhere', JSON.stringify({ sections: [] })]
  );
  const performer = await client.query(
    `INSERT INTO performers (name) VALUES ($1) RETURNING id`,
    [`Seed Performer (${ticketCount})`]
  );
  const event = await client.query(
    `INSERT INTO events (name, description, venue_id, performer_id, event_date, max_tickets_per_user)
     VALUES ($1, $2, $3, $4, now() + interval '30 days', $5)
     RETURNING id`,
    [
      `Seed Event — ${ticketCount} tickets`,
      'Generated by scripts/seed.js for load testing',
      venue.rows[0].id,
      performer.rows[0].id,
      8,
    ]
  );
  const eventId = event.rows[0].id;

  await client.query(
    `INSERT INTO tickets (event_id, seat, price, status)
     SELECT $1, 'S' || gs, 25.00, 'available'
     FROM generate_series(1, $2) AS gs`,
    [eventId, ticketCount]
  );

  return eventId;
}

async function main() {
  const { counts } = parseArgs(process.argv.slice(2));
  const client = new Client({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT) || 5432,
    user: process.env.DB_USER || 'ticketmaster',
    password: process.env.DB_PASSWORD || 'ticketmaster',
    database: process.env.DB_NAME || 'ticketmaster',
  });
  await client.connect();

  try {
    for (const count of counts) {
      const eventId = await seedEvent(client, count);
      console.log(`event ${eventId}: ${count} tickets`);
    }
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
